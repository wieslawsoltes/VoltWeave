import {mkdir,writeFile} from 'node:fs/promises';
import {createDemo} from './src/demo.js';
import {validateProject,CrossReferenceIndex,orderedPages} from './src/model.js';
import {analyzeProject} from './src/graph.js';
import {buildScene,sceneToSVG} from './src/scene.js';
import {generateDocumentation} from './src/reports.js';
const root=new URL('./examples/',import.meta.url);
await mkdir(root,{recursive:true});
const project=createDemo();validateProject(project);const analysis=analyzeProject(project),xrefs=new CrossReferenceIndex(project);
await writeFile(new URL('conveyor-drive.vw.json',root),JSON.stringify(project,null,2)+'\n');
await writeFile(new URL('conveyor-documentation.html',root),generateDocumentation(project,analysis));
for(const page of orderedPages(project))await writeFile(new URL(`conveyor-page-${page.number}.svg`,root),sceneToSVG(buildScene(project,page.id,xrefs)));
await writeFile(new URL('sample-analysis.json',root),JSON.stringify({stats:analysis.stats,issues:analysis.issues},null,2)+'\n');
console.log('Generated example project, three SVG sheets and standalone engineering documentation.');
